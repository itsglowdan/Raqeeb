def tr(text, language='en'):
    if language != 'ar' or not isinstance(text, str):
        return text
    if text in AR:
        return AR[text]
    patterns = [
        (r'Simulated task completed by (Team [AB])', lambda m: 'اكتملت المهمة الافتراضية بواسطة '+tr(m[1],language)),
        (r'Report (.+) recorded', lambda m: 'تم توثيق '+m[1]),
        (r'Pressure ([0-9.]+) < ([0-9.]+) PSI', lambda m: 'الضغط '+m[1]+' أقل من '+m[2]+' PSI'),
        (r'Flow ([0-9.]+) > ([0-9.]+) L/min', lambda m: 'التدفق '+m[1]+' أعلى من '+m[2]+' لتر/دقيقة'),
        (r'Pressure (.+)', lambda m: 'الضغط '+m[1]),
        (r'Flow (.+)', lambda m: 'التدفق '+m[1]),
        (r'Straight-line distance (.+) km', lambda m: 'المسافة بخط مستقيم '+m[1]+' كم'),
        (r'(Team [AB]): nearest configured available simulated team', lambda m: tr(m[1],language)+' هو أقرب فريق افتراضي متاح'),
        (r'(Team [AB]) failed', lambda m: 'تعطل '+tr(m[1],language)),
        (r'(Team [AB]) failed; requesting remaining teams', lambda m: 'تعطل '+tr(m[1],language)+'؛ جارٍ طلب الفرق المتبقية'),
        (r'(.+); no physical intervention', lambda m: m[1]+'؛ لا يوجد تدخل ميداني'),
    ]
    if '; ' in text:
        return '؛ '.join(tr(part, language) for part in text.split('; '))
    for pattern, replace in patterns:
        match = re.fullmatch(pattern, text)
        if match:
            return replace(match)
    return text
